/** Build-only locked assembly; client download never resolves dependencies or runs pip. */
import { createHash } from 'node:crypto'
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { parseArgs } from 'node:util'
import { readPrimaryRuntime } from '../../packages/skill/tool-workspace-dependencies/src/index.ts'
import { downloadPrimaryRuntimeAsset, unpackPrimaryRuntimeWheel } from '../primary-runtime/prepare.ts'
import { listScannerResourceFiles, verifySkillScannerResources, type SkillScannerResourceManifest } from '../../apps/desktop/src/studybuddy/skill-safety-resources.ts'
import lock from './scanner.lock.json' with { type: 'json' }
const helpers = ['worker.py', 'transport.py', 'network.py'] as const
const digest = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex')

/**
 * Identify the current worker/lock and selected runtime metadata for an independent build directory.
 * @param runtimeDirectory - Existing prepared primary runtime selected by the build owner.
 * @returns Source digest for a new candidate; no resource bytes are written or downloaded.
 */
export async function skillScannerBuildDigest(runtimeDirectory: string): Promise<string> {
  const hash = createHash('sha256').update('skill-scanner-assembly-v2')
  for (const name of ['scanner.lock.json', ...helpers]) {
    hash.update(name).update(digest(await readFile(join(import.meta.dirname, name))))
  }
  hash.update(digest(await readFile(join(runtimeDirectory, 'runtime.json'))))
  return hash.digest('hex')
}

/**
 * Assemble exact dependency wheels, rules/licenses and private helpers without changing the interpreter.
 * @param input - Windows target, existing shared runtime and an independent owned destination.
 * @returns Manifest after byte verification; stale, partial or incompatible candidates are not overwritten.
 */
export async function prepareSkillScannerResources(input: { target: 'win32-x64'; runtimeDirectory: string; destination: string }): Promise<SkillScannerResourceManifest> {
  const destination = resolve(input.destination), runtimeDirectory = resolve(input.runtimeDirectory)
  const insideRuntime = relative(runtimeDirectory, destination)
  if (input.target !== lock.target || insideRuntime === '' || (!isAbsolute(insideRuntime) && insideRuntime !== '..' && !insideRuntime.startsWith('..' + sep))) throw Error('SKILL_SAFETY_RESOURCE_INVALID')
  const primary = await readPrimaryRuntime(runtimeDirectory)
  if (primary.platform !== 'win32' || primary.arch !== 'x64' || primary.python !== lock.pythonVersion) throw Error('SKILL_SAFETY_RUNTIME_INCOMPATIBLE')
  const lockDigest = digest(await readFile(join(import.meta.dirname, 'scanner.lock.json')))
  let existing: Buffer | undefined
  try { existing = await readFile(join(destination, 'scanner-manifest.json')) }
  catch (error) { if (!(error instanceof Error && 'code' in error && error.code === 'ENOENT')) throw error }
  if (existing !== undefined) {
    const manifest = await verifySkillScannerResources(destination, runtimeDirectory, digest(existing))
    if (manifest.lockDigest !== lockDigest) throw Error('SKILL_SAFETY_RESOURCE_STALE')
    for (const name of helpers) {
      if (manifest.files.find(file => file.path === name)?.sha256 !== digest(await readFile(join(import.meta.dirname, name)))) throw Error('SKILL_SAFETY_RESOURCE_STALE')
    }
    return manifest
  }
  await mkdir(dirname(destination), { recursive: true })
  await mkdir(destination) // Never overwrite another task's existing partial directory.
  const packages = join(destination, 'packages'); await mkdir(packages)
  const cache = resolve(import.meta.dirname, '../../.dsh-build/downloads/skill-scanner-wheels-2.2.2')
  for (const wheel of lock.wheels) {
    let archive: string
    if ('url' in wheel && typeof wheel.url === 'string') archive = await downloadPrimaryRuntimeAsset(wheel.url, wheel.sha256, cache)
    else archive = join(cache, wheel.filename) // The verified source-only wheel is generated by resolve-lock.py at build time.
    const bytes = await readFile(archive)
    if (bytes.length !== wheel.size || createHash('sha256').update(bytes).digest('hex') !== wheel.sha256) throw Error('SKILL_SAFETY_RESOURCE_INVALID')
    await unpackPrimaryRuntimeWheel(archive, packages)
  }
  for (const name of helpers) await cp(join(import.meta.dirname, name), join(destination, name), { errorOnExist: true, force: false })
  const files = await listScannerResourceFiles(destination)
  const runtimeFiles = await listScannerResourceFiles(join(runtimeDirectory, 'dependencies/python'), path => path === 'Lib/site-packages' || path.includes('/__pycache__') || path.endsWith('.pyc'))
  const config = await readFile(join(packages, 'skill_scanner/data/default_policy.yaml'))
  const manifest: SkillScannerResourceManifest = { schemaVersion: 1, target: input.target, pythonVersion: lock.pythonVersion as '3.12.14', upstream: lock.upstream as SkillScannerResourceManifest['upstream'],
    lockDigest,
    configDigest: createHash('sha256').update(config).digest('hex'), files, runtimeFiles }
  const manifestBytes = Buffer.from(JSON.stringify(manifest, null, 2) + '\n')
  await writeFile(join(destination, 'scanner-manifest.json'), manifestBytes, { flag: 'wx' })
  return verifySkillScannerResources(destination, runtimeDirectory, digest(manifestBytes))
}
if (import.meta.main) {
  const { values } = parseArgs({ options: { runtime: { type: 'string' }, destination: { type: 'string' } } })
  if (!values.runtime) throw Error('Pass --runtime; --destination optionally selects a new owned build directory')
  const sourceDigest = await skillScannerBuildDigest(resolve(values.runtime))
  const destination = resolve(values.destination ?? join(import.meta.dirname, '../../.dsh-build/skill-scanner-builds/win32-x64', sourceDigest))
  const manifest = await prepareSkillScannerResources({ target: 'win32-x64', runtimeDirectory: values.runtime, destination })
  console.log(JSON.stringify({ scanner: manifest.upstream, sourceDigest, destination, manifestSha256: digest(await readFile(join(destination, 'scanner-manifest.json'))), files: manifest.files.length, addedBytes: manifest.files.reduce((sum, file) => sum + file.size, 0), sharedRuntimeFiles: manifest.runtimeFiles.length }))
}
