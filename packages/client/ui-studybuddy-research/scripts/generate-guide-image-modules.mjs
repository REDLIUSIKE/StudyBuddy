/** Encode original guide PNGs as independently requested browser chunks. */
import { readFile, readdir, writeFile } from 'node:fs/promises'
const directory = new URL('../src/client/guide-images/', import.meta.url)
for (const name of (await readdir(directory)).filter(name => name.endsWith('.png')).sort()) {
  const bytes = await readFile(new URL(name, directory))
  await writeFile(new URL(`${name.slice(0, -4)}.ts`, directory),
    `/** Original guide image; generated by scripts/generate-guide-image-modules.mjs. */\nconst image: string = ${JSON.stringify(`data:image/png;base64,${bytes.toString('base64')}`)}\nexport default image\n`)
}
